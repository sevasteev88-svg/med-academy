export function calculatePlayerAge(dateOfBirth: string): number {
  if (!dateOfBirth) return 18;
  const dob = new Date(dateOfBirth);
  const diffMs = Date.now() - dob.getTime();
  return Math.floor(diffMs / (365.25 * 86400000));
}
